import os
import re
import json
from dotenv import load_dotenv
import google.generativeai as genai

# Load environment variables from .env file if present
load_dotenv()

# List of models to try in order of preference
CANDIDATE_MODELS = [
    "gemini-1.5-flash",
    "gemini-2.0-flash",
    "gemini-1.5-pro",
    "gemini-pro"
]

def get_api_key():
    """Retrieve Gemini API key from environment or Streamlit session if available."""
    key = os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")
    if not key:
        # Check Streamlit session_state if running in streamlit
        try:
            import streamlit as st
            if "gemini_api_key" in st.session_state and st.session_state.gemini_api_key:
                key = st.session_state.gemini_api_key
        except Exception:
            pass
    return key

def ask_ai(prompt: str, model_name: str = "gemini-1.5-flash") -> str:
    """
    Send prompt to Gemini and return text response.
    Handles missing keys and API errors gracefully without crashing.
    """
    api_key = get_api_key()
    if not api_key:
        return (
            "[Warning: No Gemini API Key configured. "
            "Please set GEMINI_API_KEY in your .env file or enter it in the sidebar.]\n\n"
            "Here is a mock response for preview/testing purposes:\n"
            f"Based on your input, here is an AI-generated analysis/summary for:\n{prompt[:200]}..."
        )

    try:
        genai.configure(api_key=api_key)
        # Try candidate models if the requested one fails
        models_to_attempt = [model_name] + [m for m in CANDIDATE_MODELS if m != model_name]
        last_error = None
        for m in models_to_attempt:
            try:
                model = genai.GenerativeModel(m)
                response = model.generate_content(prompt)
                if response and hasattr(response, "text") and response.text:
                    return response.text
            except Exception as e:
                last_error = e
                continue
        if last_error:
            raise last_error
        return "No response generated by the model."
    except Exception as e:
        return f"[AI Error: {str(e)}]"

def clean_json_text(text: str) -> str:
    """Extract clean JSON string from LLM output (removes markdown backticks)."""
    text = text.strip()
    # Match markdown json block ```json ... ``` or ``` ... ```
    match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text)
    if match:
        return match.group(1).strip()
    
    # Try finding the first '{' and last '}' or '[' and ']'
    start_brace = text.find("{")
    start_bracket = text.find("[")
    
    if start_brace != -1 and (start_bracket == -1 or start_brace < start_bracket):
        end_brace = text.rfind("}")
        if end_brace != -1:
            return text[start_brace:end_brace + 1]
    elif start_bracket != -1:
        end_bracket = text.rfind("]")
        if end_bracket != -1:
            return text[start_bracket:end_bracket + 1]
            
    return text

def ask_ai_json(prompt: str, model_name: str = "gemini-1.5-flash"):
    """
    Send prompt to Gemini and return parsed JSON data.
    Gracefully handles markdown formatting, malformed JSON, and API failures.
    """
    api_key = get_api_key()
    if not api_key:
        # Provide sensible offline fallback JSON depending on prompt keywords
        return get_fallback_json(prompt)

    raw_response = ask_ai(prompt, model_name=model_name)
    cleaned = clean_json_text(raw_response)
    try:
        return json.loads(cleaned)
    except Exception as e:
        # Attempt minimal repair if trailing commas or quote mismatch
        try:
            # Replace single quotes with double quotes if needed
            repaired = re.sub(r",\s*([\]}])", r"\1", cleaned)
            return json.loads(repaired)
        except Exception:
            # Return a fallback or dict with error info
            return get_fallback_json(prompt, error_msg=f"Failed to parse JSON: {e}. Raw response: {raw_response[:200]}")

